# ------------------------------------------------------------
# Build Comparison Maps
# ------------------------------------------------------------

$ExactMap = @{}
$NameMap  = @{}

foreach ($Setting in $AllSettings)
{
    $NameKey =
        @(
            $Setting.Class
            $Setting.Extension
            $Setting.Category
            $Setting.SettingName
        ) -join $Sep

    $ExactKey = $NameKey + $Sep + $Setting.Value + $Sep + $Setting.State

    if (-not $ExactMap.ContainsKey($ExactKey))
    {
        $ExactMap[$ExactKey] = @{
            Item = $Setting
            GPOs = [System.Collections.Generic.HashSet[string]]::new()
        }
    }

    [void]$ExactMap[$ExactKey].GPOs.Add($Setting.GPOName)

    if (-not $NameMap.ContainsKey($NameKey))
    {
        $NameMap[$NameKey] = [System.Collections.ArrayList]::new()
    }

    [void]$NameMap[$NameKey].Add($Setting)
}

$SortedExactKeys = @($ExactMap.Keys | Sort-Object)
$SortedNameKeys  = @($NameMap.Keys | Sort-Object)

# Per setting name: how many GPOs configure it, and how many different
# configurations exist across those GPOs. A GPO with several rows for one
# name is treated as one configuration (the set of its values), so multi-row
# settings do not look like conflicts by themselves.

$NameInfo = @{}

foreach ($Key in $SortedNameKeys)
{
    $ByGpo = @{}

    foreach ($Item in $NameMap[$Key])
    {
        if (-not $ByGpo.ContainsKey($Item.GPOName))
        {
            $ByGpo[$Item.GPOName] = [System.Collections.Generic.List[string]]::new()
        }

        $ByGpo[$Item.GPOName].Add($Item.Value + $Sep + $Item.State)
    }

    $Signatures =
        @(
            foreach ($Gpo in $ByGpo.Keys)
            {
                (@($ByGpo[$Gpo] | Sort-Object -Unique)) -join $Sep
            }
        )

    $NameInfo[$Key] = [PSCustomObject]@{
        GpoCount       = $ByGpo.Count
        SignatureCount = @($Signatures | Sort-Object -Unique).Count
    }
}

# ------------------------------------------------------------
# Common Exact
# ------------------------------------------------------------

$CommonSettings =
    @(
        foreach ($Key in $SortedExactKeys)
        {
            $Entry = $ExactMap[$Key]

            if ($Entry.GPOs.Count -eq $TotalGPOs)
            {
                $Entry.Item
            }
        }
    )

# ------------------------------------------------------------
# Common By Name
# ------------------------------------------------------------

$CommonSettingsByName =
    @(
        foreach ($Key in $SortedNameKeys)
        {
            $Info = $NameInfo[$Key]

            if ($Info.GpoCount -eq $TotalGPOs)
            {
                $First = $NameMap[$Key][0]

                [PSCustomObject]@{
                    Class               = $First.Class
                    Extension           = $First.Extension
                    Category            = $First.Category
                    SettingName         = $First.SettingName
                    Value               = $First.Value
                    State               = $First.State
                    SameValueEverywhere = ($Info.SignatureCount -eq 1)
                }
            }
        }
    )

# ------------------------------------------------------------
# Unique (configured in some GPOs, not all)
# ------------------------------------------------------------

$UniqueSettings =
    @(
        foreach ($Key in $SortedNameKeys)
        {
            $Info = $NameInfo[$Key]

            if ($Info.GpoCount -ge $TotalGPOs)
            {
                continue
            }

            $ConfigMap = @{}

            foreach ($Item in $NameMap[$Key])
            {
                $ConfigKey = $Item.Value + $Sep + $Item.State

                if (-not $ConfigMap.ContainsKey($ConfigKey))
                {
                    $ConfigMap[$ConfigKey] = @{
                        Item = $Item
                        GPOs = [System.Collections.Generic.HashSet[string]]::new()
                    }
                }

                [void]$ConfigMap[$ConfigKey].GPOs.Add($Item.GPOName)
            }

            foreach ($ConfigKey in @($ConfigMap.Keys | Sort-Object))
            {
                $Entry = $ConfigMap[$ConfigKey]

                [PSCustomObject]@{
                    Class               = $Entry.Item.Class
                    Extension           = $Entry.Item.Extension
                    Category            = $Entry.Item.Category
                    SettingName         = $Entry.Item.SettingName
                    Value               = $Entry.Item.Value
                    State               = $Entry.Item.State
                    PresentIn           = (@($Entry.GPOs | Sort-Object) -join "; ")
                    ConfiguredInGPOs    = $Info.GpoCount
                    ValuesDiffer        = ($Info.SignatureCount -gt 1)
                }
            }
        }
    )

# ------------------------------------------------------------
# Conflicts (more than one GPO, different configuration)
# ------------------------------------------------------------

$ConflictingSettings =
    @(
        foreach ($Key in $SortedNameKeys)
        {
            $Info = $NameInfo[$Key]

            if ($Info.GpoCount -gt 1 -and $Info.SignatureCount -gt 1)
            {
                $NameMap[$Key] | Sort-Object GPOName
            }
        }
    )

# ------------------------------------------------------------
# Duplicates (more than one GPO, identical configuration)
# ------------------------------------------------------------

$DuplicateSettings =
    @(
        foreach ($Key in $SortedNameKeys)
        {
            $Info = $NameInfo[$Key]

            if ($Info.GpoCount -gt 1 -and $Info.SignatureCount -eq 1)
            {
                $First = $NameMap[$Key][0]
                $Gpos  = @($NameMap[$Key].GPOName | Sort-Object -Unique)

                [PSCustomObject]@{
                    Class       = $First.Class
                    Extension   = $First.Extension
                    Category    = $First.Category
                    SettingName = $First.SettingName
                    Value       = $First.Value
                    State       = $First.State
                    PresentIn   = ($Gpos -join "; ")
                }
            }
        }
    )

