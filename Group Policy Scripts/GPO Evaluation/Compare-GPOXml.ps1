<#
.SYNOPSIS
Compare GPO XML exports generated by Get-GPOReport.

.DESCRIPTION
Processes one or more GPO XML exports and generates comparison, inventory,
conflict, duplicate, deprecated-policy and Intune migration reports.

XML parsing is performed by GPOCompare.psm1. This script:
- Loads the XML files and calls Get-GPOSettingsFromXml
- Builds the comparison maps
- Generates and exports the CSV reports

Settings are compared case-insensitively. Firewall rules are exported only to
FirewallRules.csv; firewall profile settings are part of the normal comparison.

Reports written to OutputFolder:

ParsedSettings.csv
    Every parsed setting (raw parser output).

CommonSettings.csv
    Exact match: identical Class, Extension, Category, SettingName, Value and
    State in every GPO.

CommonSettingsByName.csv
    Setting configured in every GPO regardless of value.
    SameValueEverywhere = False means the values differ between GPOs.

UniqueSettings.csv
    Setting configured in some GPOs but not all. One row per distinct value;
    PresentIn lists the GPOs that use that value. ValuesDiffer = True means the
    GPOs that do configure it disagree.

ConflictingSettings.csv
    Setting configured in more than one GPO with different values. A GPO that
    has several rows for one setting is compared as a set of values.

DuplicateSettings.csv
    Setting configured identically in more than one GPO (PresentIn).

DeprecatedPolicies.csv
    Settings that match DeprecatedPoliciesReference.md.

MissingSettingsMatrix.csv
    Present / Missing per GPO for every setting name.

FirewallRules.csv
    Inventory of firewall rules (Inbound and Outbound).

IntuneMigrationCandidates.csv
    Every setting with its Intune mapping from the mapping file, plus a
    Deprecated flag. MappingStatus is one of the values defined in the mapping
    file, or Unmapped (no matching entry) or MappingFileMissing.

UnclassifiedSettings.csv
    Unsupported extensions or sections, settings without a name, and parser
    errors. Anything listed here is NOT part of the comparison reports.

ParserFailures.csv
    XML files that could not be parsed at all. Those GPOs are excluded from
    the GPO total.

RunStatistics.csv
    Counts for the run. Every other report has a count here that equals its
    number of rows (for example Conflicts for ConflictingSettings.csv).

GPOCompareXml.xlsx (only with -OutputFormat Excel)
    One workbook, written instead of the CSV files, with one worksheet per
    report in this order: RunStatistics, CommonSettings, UniqueSettings,
    DeprecatedPolicies, FirewallRules, IntuneMigrationCandidates,
    DuplicateSettings, ConflictingSettings, ParsedSettings, then the others.
    Every worksheet is an Excel table with a blue header (table style
    Medium2) and a frozen header row. RunStatistics is shown as a
    Statistic / Value table; each statistic that counts a worksheet's rows
    is a link to that worksheet. Text values are stored exactly as text;
    counts are numbers and True/False values are Excel TRUE/FALSE.

.PARAMETER XmlFolder
Folder containing XML exports (Get-GPOReport -ReportType Xml).

.PARAMETER OutputFolder
Folder where generated reports are written. Created if it does not exist.

.PARAMETER ModulePath
Path to GPOCompare.psm1. Default: next to this script.

.PARAMETER IntuneMappingPath
Path to the Intune mapping file. Default: intunemapping.json next to this
script. The file is optional: if it does not exist a warning is shown and the
run continues (mapping columns show MappingFileMissing). A file that exists
but cannot be parsed stops the run.

.PARAMETER DeprecatedReferencePath
Path to DeprecatedPoliciesReference.md. Default: next to this script. If it
does not exist a warning is shown and no deprecated matches are reported.

.PARAMETER FilePrefix
Text added to the start of every output file name, followed by a hyphen.
For example, LS writes LS-CommonSettings.csv instead of CommonSettings.csv.
If this parameter is not given, the script asks for the prefix; press Enter
for no prefix. Pass -FilePrefix "" to skip the question and use no prefix.
In a session that cannot ask (for example -NonInteractive), no prefix is
used.

.PARAMETER OutputFormat
CSV or Excel. CSV writes one CSV file per report. Excel writes one workbook,
GPOCompareXml.xlsx (with the file name prefix, if one is used), with one worksheet
per report and no CSV files. If this parameter is not given, the script
asks (C or E; press Enter for CSV). In a session that cannot ask (for
example -NonInteractive), CSV is used.

Excel output needs the ImportExcel module; Excel itself is not needed. If
the module is not installed, the script installs it for the current user
from the PowerShell Gallery (Install-Module ImportExcel -Scope CurrentUser,
plus the NuGet package provider if missing). If it cannot be installed, a
warning is shown and the output continues as CSV files. If the workbook
cannot be written (for example, the file is open in Excel), the reports are
written as CSV files instead. A value longer than 32767 characters (the
Excel cell limit) is cut to that length in the workbook, with a warning.

.EXAMPLE
.\Compare-GPOXml.ps1 -XmlFolder "C:\GPOProject\XML" -OutputFolder "C:\GPOProject\Output"

.EXAMPLE
.\Compare-GPOXml.ps1 -XmlFolder "C:\GPOProject\XML" -OutputFolder "C:\GPOProject\Output" -FilePrefix LS

.EXAMPLE
.\Compare-GPOXml.ps1 -XmlFolder "C:\GPOProject\XML" -OutputFolder "C:\GPOProject\Output" -FilePrefix LS -OutputFormat Excel

